router.post("/calibrationSystem/LicenseStatus", (req, res) => {
    const { uuid, licenseKey } = req.body;
    pool.getConnection((err, connection) => {
        if (err) return res.status(202).json({ errNo: 5, errMsg: err });
        connection.query("select * from calibrationlicenses where sn = ? ORDER BY createdatetime DESC limit 1", [licenseKey], (error, rows) => {
            if (error || rows.length === 0) {
                res.status(202).json({ errNo: 1, errMsg: "not existed" });
            } else {
                const obj = rows[0];
                if (obj.state === 0) {
                    connection.query("update calibrationlicenses set localid=?, state=1 where sn=?", [uuid, licenseKey], (err) => {
                        if (err) res.status(202).json({ errNo: 5, errMsg: "sql error" });
                        else res.status(202).json({ errNo: 0, errMsg: "license valid" });
                    });
                } else if (obj.state === 1 && obj.localid === uuid) {
                    res.status(202).json({ errNo: 0, errMsg: "license valid" });
                } else {
                    res.status(202).json({ errNo: 4, errMsg: "invalid state" });
                }
            }
            connection.release();
        });
    });
});

