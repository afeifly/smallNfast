// --- S520 Routes ---
function getS520license(req, res, kw) {
    let sql = 'select s.id,s.sn,s.note,s.license,s.createdatetime from s520licenses s';
    sql += " ORDER BY s.createdatetime DESC limit 200";
    pool.getConnection((err, connection) => {
        if (err) return res.status(202).json({ err });
        connection.query(sql, (error, rows) => {
            if (error) res.status(202).json({ err: error });
            else res.status(200).json(rows);
            connection.release();
        });
    });
}

router.get(constants.API_URL + constants.API_URL_S520_LICENSES, (req, res) => {
    getS520license(req, res, req.query.kw);
});

router.post(constants.API_URL + constants.API_URL_S520_LICENSES, (req, res) => {
    const { sn, note, license } = req.body;
    // Prefer the license generated by the frontend (JS version of license_gen.py)
    const key = license || crypto.base64ToHex(crypto.encryption(sn, 'cQfTjWnZr4u7x!A%D*F-JaNdRgUkXp2s'));
    const sn_props = [[sn, note, key, new Date()]];
    pool.getConnection((err, connection) => {
        if (err) return res.status(202).json({ err });
        connection.query('insert into s520licenses(sn, note, license, createdatetime) values ?', [sn_props], (error, done) => {
            if (error) {
                res.status(200).json({ msg: error });
            } else {
                helpers.createEvent(connection, req.session.loginName, constants.EVENT_TYPE_CREATE, constants.PRODUCT_TYPE_S520, sn + " with note: " + note);
                res.json({ license: key });
            }
            connection.release();
        });
    });
});

