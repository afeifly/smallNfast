router.post('/s4cusregistration', (req, res) => {
    const { deviceid, sn } = req.body;
    pool.getConnection((err, connection) => {
        if (err) return res.status(400).json({ err });
        connection.query('select * from s4cus_serialnumber where sn = ?', [sn], (error, lrows) => {
            if (error) {
                res.status(400).json({ err: error });
            } else if (lrows.length === 0) {
                res.status(202).json({ err: 'serial number not found' });
            } else {
                const row = lrows[0];
                if (row.state === 0) {
                    connection.query('update s4cus_serialnumber set state = 1, deviceid = ? where sn = ?', [deviceid, sn], (err) => {
                        if (err) res.status(202).json({ err: 'register fail' });
                        else res.status(200).send(crypto.encryptAES(JSON.stringify(row)));
                    });
                } else if (row.state === 1 && deviceid === row.deviceid) {
                    res.status(200).send(crypto.encryptAES(JSON.stringify(row)));
                } else {
                    res.status(202).json({ err: 'bound to other device or blocked' });
                }
            }
            connection.release();
        });
    });
});

